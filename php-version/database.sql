CREATE DATABASE IF NOT EXISTS kroon_tg CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kroon_tg;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('ADMIN','PROVIDER') NOT NULL DEFAULT 'PROVIDER',
 active TINYINT(1) NOT NULL DEFAULT 1,
 phone VARCHAR(40) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_users_role_active(role,active)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS installations (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 banner VARCHAR(100) NOT NULL,
 store_name VARCHAR(180) NOT NULL,
 city VARCHAR(100) NOT NULL,
 supervisor VARCHAR(150) NULL,
 phone VARCHAR(40) NULL,
 status ENUM('A_REPERER','MESURES_PRISES','PROD','DISPATCH','INSTALLE') NOT NULL DEFAULT 'A_REPERER',
 tech_sheet_url TEXT NULL,
 deadline DATE NULL,
 measurements_json JSON NULL,
 photos_json JSON NOT NULL,
 provider_id INT UNSIGNED NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_store (banner,store_name,city),
 INDEX idx_install_provider_status(provider_id,status),
 INDEX idx_install_city_status(city,status),
 CONSTRAINT fk_install_provider FOREIGN KEY(provider_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
